// pharmacyKey.js — مفتاح مطابقة موحّد لأسماء الصيدليات.
// ────────────────────────────────────────────────────────────────────────────
// المشكلة: كان لكل مسار تطبيعه الخاص (السيرفر، وثلاث نسخ في الواجهة)، فتختلف
// الأسماء بين الملفات والشاشات. والمسألة الأعمق: «صيدلية الامل» و«الامل»
// و«ص. الامل» صيدلية واحدة، لكنها تُعدّ ثلاث صيدليات.
//
// هذا المفتاح يُزيل ما لا يميّز الصيدلية: الحركات العربية الموحّدة، علامات
// الترقيم، «ال» التعريف، وكلمات الوصف العامة (صيدلية / ص / مكتب / مذخر).
// النسخة في الواجهة: src/lib/pharmacyKey.ts — يجب أن تبقى مطابقة لهذا الملف
// حرفياً (تغطيها scripts/test-pharmacy-key.mjs).
// ════════════════════════════════════════════════════════════════════════════

const GENERIC_TOKENS = new Set(['صيدليه', 'صيدلي', 'ص', 'مكتب', 'مذخر']);

export function pharmacyKey(name) {
  const s = String(name ?? '')
    .trim()
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ء/g, '')
    .replace(/[ً-ٟ]/g, '')   // التشكيل
    .replace(/ـ/g, '')        // التطويل
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, ' '); // الترقيم والرموز → فراغ
  return s
    .split(/\s+/)
    .filter(Boolean)
    .map(t => (t.length > 3 && t.startsWith('ال') ? t.slice(2) : t))
    .filter(t => !GENERIC_TOKENS.has(t))
    .join(' ');
}
