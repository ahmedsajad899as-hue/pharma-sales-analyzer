// لماذا يستحق اختباراً: فشل المطابقة لا يُسقط استيراداً ولا يرمي خطأً — الصف
// بلا مندوب محسوم يُهمَل عند الحفظ، فتظهر أعداد الزيارات أقل من الملف بلا سبب
// ظاهر. حدث هذا فعلاً: حسابات المندوبين مسمّاة «الاسم/ المنطقة ph» بينما ملف
// الـCRM يحمل الاسم مجرَّداً، فلم يتطابق أحد، وسقطت درجة التشابه إلى صفر فلم
// يُسأل المستخدم حتى — فُقدت آلاف الزيارات صامتةً.
// ════════════════════════════════════════════════════════════════════════════

import { buildRepIndex, matchRepName, repCoreName, repNameScore } from '../server/lib/repNameMatch.js';

let failed = 0;
const check = (label, actual, expected) => {
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) { failed++; console.log(`✗ ${label}\n    نتيجة: ${JSON.stringify(actual)}\n    متوقَّع: ${JSON.stringify(expected)}`); }
  else console.log(`✓ ${label}`);
};

// تسمية الحسابات الفعلية في الإنتاج — الاسم ثم «/ المنطقة» ثم لاحقة ph، بمسافة
// قبل السلاش أحياناً وبدونها أحياناً (كلاهما موجود في نفس الحساب).
const REPS = [
  { id: 1, name: 'عبدالله عمر/ كرخ غربي ph',   company: 'humanis' },
  { id: 2, name: 'مصطفى زكي / كرخ شمالي ph',   company: 'humanis' },
  { id: 3, name: 'ابراهيم / مدينة ph',          company: 'humanis' },
  { id: 4, name: 'حيدر صباح/ رصافة غربي ph',    company: 'humanis' },
  { id: 5, name: 'سعد الدين كريم',              company: 'deva'    },
];
const index = buildRepIndex(REPS);
const m = raw => { const r = matchRepName(raw, index); return { status: r.status, id: r.rep?.id ?? null }; };

// ── نواة الاسم ───────────────────────────────────────────────────────────────
check('نواة: لاحقة بسلاش بلا مسافة', repCoreName('عبدالله عمر/ كرخ غربي ph'), 'عبدالله عمر');
check('نواة: لاحقة بسلاش بمسافة',    repCoreName('مصطفى زكي / كرخ شمالي ph'), 'مصطفى زكي');
check('نواة: اسم بلا لاحقة يبقى كما هو', repCoreName('سعد الدين كريم'), 'سعد الدين كريم');

// ── الحالة التي كسرت فعلاً: اسم مجرَّد من الملف ← حساب بلاحقة منطقة ──────────
check('اسم مجرَّد يطابق حساباً بلاحقة منطقة', m('عبدالله عمر'), { status: 'exact', id: 1 });
check('نفس الحالة بمسافة قبل السلاش',        m('مصطفى زكي'),   { status: 'exact', id: 2 });
check('اسم من كلمة واحدة (كان صفر تشابه)',   m('ابراهيم'),     { status: 'exact', id: 3 });
check('تهجئة ملتصقة/منفصلة لنفس الاسم',      m('عبد الله عمر'), { status: 'exact', id: 1 });
check('الاسم الكامل كما هو في الحساب',       m('عبدالله عمر/ كرخ غربي ph'), { status: 'exact', id: 1 });
check('تطابق تام لاسم بلا لاحقة',            m('سعد الدين كريم'), { status: 'exact', id: 5 });
check('اختلاف التاء المربوطة في لاحقة المنطقة', m('حيدر صباح'), { status: 'exact', id: 4 });

// ── الالتباس يُسأل عنه ولا يُخمَّن ولا يُهمَل ────────────────────────────────
// نفس الشخص بحساب لكل شركة — اختيار أحدهما عشوائياً يَنسب زياراته لشركة أخرى.
const dupIndex = buildRepIndex([
  ...REPS,
  { id: 6, name: 'عبدالله عمر / رصافة ph', company: 'deva' },
]);
const dup = matchRepName('عبدالله عمر', dupIndex);
check('اسم مكرَّر بين شركتين → سؤال لا تخمين', dup.status, 'ask');
check('السؤال يصل ومعه المرشَّحان', dup.suggestions.map(s => s.id).sort(), [1, 6]);
check('المرشَّح يحمل شركته للتمييز', dup.suggestions.map(s => s.company).sort(), ['deva', 'humanis']);

// ── اسم غريب تماماً يبقى خارج النطاق ────────────────────────────────────────
check('اسم لا يشبه أحداً', m('شركة النقل العام'), { status: 'none', id: null });

// ── درجة التشابه لم تتغيّر لمستهلكيها الآخرين (ميركاتو) ─────────────────────
check('تشابه: احتواء تام',        repNameScore('محمد باقر', 'محمد باقر مرتضى') > 0.8, true);
check('تشابه: كلمة واحدة مشتركة', repNameScore('محمد علي', 'محمد حسين'), 0);

console.log(failed === 0 ? '\n✅ كل الحالات نجحت' : `\n❌ ${failed} حالة فشلت`);
process.exit(failed === 0 ? 0 : 1);
